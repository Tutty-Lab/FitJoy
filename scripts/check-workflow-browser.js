// Run against a local dev server in an isolated Playwright CLI browser session.
// npx --yes --package @playwright/cli playwright-cli -s=workflow run-code --filename scripts/check-workflow-browser.js
async page => {
  await page.clock.resume()
  const base='http://127.0.0.1:5173'
  const assert=(value,message)=>{if(!value)throw Error(message)}
  const fixture=async({day=1,language='vi',done=0,complete=false,onboarded=true,checked=true}={})=>{
    await page.goto(base+'/login')
    await page.evaluate(({day,language,done,complete,onboarded,checked})=>{
      localStorage.clear()
      const date=new Date(), pad=n=>String(n).padStart(2,'0')
      const key=`${date.getFullYear()}-${pad(date.getMonth()+1)}-${pad(date.getDate())}`
      const completed=Array.from({length:day-1},(_,i)=>i+1)
      if(complete)completed.push(day)
      const lessonCompletions=completed.flatMap(d=>Array.from({length:d===day?done:3},(_,i)=>`${d}:${i+1}`))
      localStorage.setItem('fitjoy.lang',language)
      localStorage.setItem('fitjoy.profile',JSON.stringify({username:'workflow-preview',name:'Preview',role:'admin',gameOnboarded:onboarded,onboarded:true,checkPostponed:checked,lessonCompletions,dayDates:complete?{[day]:key}:{}}))
      localStorage.setItem('fitjoy.completed',JSON.stringify(completed))
      localStorage.setItem('fitjoy.activeDates',JSON.stringify(complete?[key]:[]))
    },{day,language,done,complete,onboarded,checked})
    await page.goto(base+'/')
  }
  const prepareCurrent=async()=>{
    await page.locator('.is-current button').click()
    await page.getByRole('button',{name:'Tiếp tục',exact:true}).click()
    await page.getByRole('heading',{name:'Lời nhắn dành cho hôm nay',exact:true}).waitFor()
    await page.getByRole('button',{name:'Tiếp tục',exact:true}).click()
    await page.getByRole('heading',{name:'Phút tập tiếp theo của bạn',exact:true}).waitFor()
  }
  await page.setViewportSize({width:390,height:844})
  for(const language of ['vi','de']) {
    await fixture({language})
    await page.locator('.journey-map').waitFor()
    assert(await page.locator('.adventure-regions').count()===0,'region selector remains')
    assert(await page.locator('.adventure-map').count()===9,'all nine map chapters')
    assert(await page.locator('.adventure-map-title').count()===0,'map caption remains')
    assert((await page.getByRole('navigation').innerText()).trim()==='','navigation labels remain')
    assert(await page.getByRole('navigation').locator('svg').count()===3,'three cartoon navigation icons')
    assert(await page.locator('nav[aria-label] a').count()===3,'three navigation destinations')
    await page.screenshot({path:`output/workflow-home-${language}.png`,scale:'css',animations:'disabled'})
    await page.goto(base+'/days/1')
    const prep=page.getByRole('progressbar')
    await prep.waitFor()
    assert(await prep.getAttribute('aria-valuenow')==='1','day preparation begins at one')
    assert(!/bonus/i.test(await page.locator('body').innerText()),'bonus appears before completion')
    assert(await page.getByRole('navigation').count()===0,'preparation should have no competing navigation')
    const next=language==='vi'?'Tiếp tục':'Weiter', back=language==='vi'?'Quay lại':'Zurück'
    await page.getByRole('button',{name:next,exact:true}).click()
    await page.getByRole('heading',{name:language==='vi'?'Lời nhắn dành cho hôm nay':'Dein Gedanke für heute',exact:true}).waitFor()
    assert(await prep.getAttribute('aria-valuenow')==='2','affirmation is step two')
    await page.getByRole('button',{name:back,exact:true}).click()
    await page.getByRole('heading',{name:language==='vi'?'Thật vui vì bạn ở đây':'Schön, dass du da bist',exact:true}).waitFor()
    await page.getByRole('button',{name:next,exact:true}).click()
    await page.getByRole('heading',{name:language==='vi'?'Lời nhắn dành cho hôm nay':'Dein Gedanke für heute',exact:true}).waitFor()
    await page.getByRole('button',{name:next,exact:true}).click()
    await page.getByRole('heading',{name:language==='vi'?'Phút tập tiếp theo của bạn':'Deine nächste Minute',exact:true}).waitFor()
    assert(await prep.getAttribute('aria-valuenow')==='3','practice handoff is step three')
    await page.screenshot({path:`output/day-preparation-${language}.png`,scale:'css',animations:'disabled'})
    await page.getByRole('link',{name:language==='vi'?'Bắt đầu phút 1':'Minute 1 starten',exact:true}).click()
    await page.getByRole('button',{name:language==='vi'?'Bắt đầu tập · 60 giây':'Übung starten · 60 Sekunden',exact:true}).waitFor()
    for(const route of ['/calendar','/story','/reminders','/profile','/streak','/compare']) {
      await page.goto(base+route)
      await page.locator('h1,h2').first().waitFor()
      assert(!await page.locator('.story-character').count(),'mascot playground remains')
      await page.setViewportSize({width:320,height:740})
      assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'overflow '+route)
      await page.setViewportSize({width:390,height:844})
    }
    await page.goto(base+'/story')
    await page.locator('.flow-chapter').first().waitFor()
    assert(await page.locator('.flow-chapter').count()===9,'nine story chapters')
    assert(await page.locator('.story-episode').count()===10,'current chapter contains ten days')
    assert(await page.locator('.story-episode.earned').count()===0,'unearned episodes must not be marked earned')
  }
  for(const day of [30,31,60,61,90]) {
    await fixture({day})
    await page.locator('.journey-map').waitFor()
    await page.goto(base+'/story')
    await page.locator('.flow-chapter[open]').waitFor()
    assert((await page.locator('.flow-chapter[open]>summary').innerText()).includes(`Chương ${Math.ceil(day/10)}`),'wrong story chapter')
    await page.goto(base+`/workouts/${Math.min(90,day+1)}`)
    if(day<90)await page.waitForURL(base+'/')
    if(day<90)assert(new URL(page.url()).pathname==='/','future workout must redirect')
  }
  // Fresh onboarding, postpone check, resume saved draft.
  await fixture({onboarded:false,checked:false})
  await page.getByRole('heading',{name:'Một tấm thiệp. Một hành trình cùng nhau.'}).waitFor()
  await page.getByRole('button',{name:'Tiếp tục',exact:true}).click()
  await page.getByRole('button',{name:'Tiếp tục',exact:true}).click()
  await page.getByRole('button',{name:'Đến bài tự kiểm tra',exact:true}).click()
  await page.getByRole('button',{name:'Làm bài tự kiểm tra sau',exact:true}).click()
  await page.locator('.journey-map').waitFor()
  // Determine actual task id from the UI to avoid mirroring the test implementation.
  await page.goto(base+'/check/start')
  await page.getByRole('button',{name:'Sẵn sàng – bắt đầu thôi!',exact:true}).click()
  await page.getByRole('button',{name:'Bắt đầu',exact:true}).click()
  const input=page.getByRole('textbox').first()
  await input.fill('12')
  await page.getByRole('button',{name:'5',exact:true}).click()
  await page.getByRole('button',{name:'Tiếp',exact:true}).click()
  await page.getByRole('button',{name:'Tiếp tục sau',exact:true}).click()
  await page.goto(base+'/check/start')
  await page.getByRole('heading',{name:'Tự kiểm tra',exact:true}).waitFor()
  assert((await page.locator('header').innerText()).includes('2/18'),'draft should resume at second task')
  // Controlled media + virtual clock: countdown and transition tests, no server writes.
  await page.addInitScript(()=>{
    HTMLMediaElement.prototype.play=function(){this.dispatchEvent(new Event('playing'));return Promise.resolve()}
    HTMLMediaElement.prototype.pause=function(){this.dispatchEvent(new Event('pause'))}
  })
  await page.clock.install()
  await fixture()
  await prepareCurrent()
  await page.getByRole('link',{name:'Bắt đầu phút 1',exact:true}).click()
  assert(await page.getByRole('navigation').count()===0,'hide navigation while training')
  assert(await page.getByRole('button',{name:'Xem lại hướng dẫn',exact:true}).count()===0,'duplicate replay button')
  await page.getByRole('button',{name:'Bắt đầu tập · 60 giây',exact:true}).click()
  await page.getByRole('timer').waitFor()
  await page.clock.runFor(10000)
  await page.getByRole('button',{name:'Tạm dừng',exact:true}).click()
  const paused=await page.getByRole('timer').innerText()
  await page.clock.runFor(5000)
  assert(await page.getByRole('timer').innerText()===paused,'pause consumes time')
  await page.getByRole('button',{name:'Quay lại',exact:true}).click()
  await page.getByRole('dialog').waitFor()
  await page.keyboard.press('Escape')
  assert(!await page.getByRole('dialog').count(),'Escape should stay in practice')
  await page.getByRole('button',{name:'Tiếp tục',exact:true}).click()
  await page.clock.runFor(61000)
  await page.getByRole('heading',{name:'Làm tốt lắm!',exact:true}).waitFor()
  assert(await page.locator('.story-reward').count()===1,'first minute reveals story')
  await page.getByRole('link',{name:'Đến phút 2',exact:true}).click()
  await page.getByRole('button',{name:'Bắt đầu tập · 60 giây',exact:true}).click()
  await page.clock.runFor(61000)
  await page.getByRole('heading',{name:'Làm tốt lắm!',exact:true}).waitFor()
  assert(await page.locator('.story-reward').count()===0,'second minute must not reaward story')
  await page.getByRole('link',{name:'Đến phút 3',exact:true}).click()
  await page.getByRole('button',{name:'Bắt đầu tập · 60 giây',exact:true}).click()
  await page.clock.runFor(61000)
  await page.getByRole('link',{name:'Về Hôm nay',exact:true}).click()
  await page.locator('.journey-map').waitFor()
  await prepareCurrent()
  assert((await page.getByRole('status').innerText()).includes('Ngày 2 mở vào ngày mai'),'tomorrow message')
  assert(await page.evaluate(()=>JSON.parse(localStorage.getItem('fitjoy.completed')).length)===1,'three minutes must yield one day')
  await page.evaluate(()=>{const p=JSON.parse(localStorage.getItem('fitjoy.profile'));p.dayDates[1]='2000-01-01';localStorage.setItem('fitjoy.profile',JSON.stringify(p))})
  await page.goto(base+'/')
  await page.locator('.journey-map').waitFor()
  assert((await page.locator('.is-current button').getAttribute('aria-label')).includes('Ngày 2:'),'new calendar day should open day two')
  // Finished/review states, both small and tablet widths.
  await fixture({day:90,done:3,complete:true})
  await prepareCurrent()
  await page.getByRole('link',{name:'Bắt đầu tự kiểm tra cuối hành trình',exact:true}).waitFor()
  await page.getByRole('link',{name:'Bắt đầu tự kiểm tra cuối hành trình',exact:true}).click()
  await page.getByRole('button',{name:'Bắt đầu tự kiểm tra',exact:true}).click()
  await page.getByRole('button',{name:'Sẵn sàng – bắt đầu so sánh!',exact:true}).click()
  for(let i=0;i<18;i++){
    await page.getByRole('textbox').first().fill('10')
    await page.getByRole('button',{name:'5',exact:true}).click()
    await page.getByRole('button',{name:i===17?'So sánh kết quả':'Tiếp',exact:true}).click()
  }
  await page.getByText('Kết quả của tôi',{exact:true}).waitFor()
  await page.getByRole('link',{name:'Về Hôm nay',exact:true}).click()
  await prepareCurrent()
  await page.getByRole('link',{name:'Xem kết quả',exact:true}).waitFor()

  for(const width of [320,1032]) {
    await page.setViewportSize({width,height:844})
    assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'responsive overflow')
  }
  await page.setViewportSize({width:390,height:844})
  await fixture({day:31})
  await page.locator('.journey-map').waitFor()
  await page.screenshot({path:'output/workflow-forest.png',scale:'css',animations:'disabled'})
}
